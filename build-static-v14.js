'use strict';
// Build the v14 browser bundle: v14-terminal indicators.js + agents/* + aggregator.js -> site-v14/engine-v14.js
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SRC = path.join(ROOT, 'v14-terminal');
const OUT = path.join(ROOT, 'site-v14', 'engine-v14.js');

function wrap(id, file) {
  const body = fs.readFileSync(file, 'utf8');
  return [
    `  __define('${id}', function () {`,
    `    var module = { exports: {} };`,
    `    var exports = module.exports;`,
    `    var require = __req;`,
    body,
    `    return module.exports;`,
    `  });`
  ].join('\n');
}

const banner = [
  '/* XAU/USDT OMNISCIENT SCALPER v14.0 — browser engine bundle (generated by build-static-v14.js) */',
  '(function (root) {',
  `  'use strict';`,
  `  var __m = {};`,
  `  function __define(id, factory) { __m[id] = factory(); }`,
  `  function __req(id) { id = String(id).replace(/^\\.\\//, ''); return __m[id]; }`
].join('\n');

const modules = [
  ['indicators.js', path.join(SRC, 'indicators.js')],
  ['agents/engine.js', path.join(SRC, 'agents', 'engine.js')],
  ['agents/part1.js', path.join(SRC, 'agents', 'part1.js')],
  ['agents/part2.js', path.join(SRC, 'agents', 'part2.js')],
  ['agents/part3.js', path.join(SRC, 'agents', 'part3.js')],
  ['agents/part4.js', path.join(SRC, 'agents', 'part4.js')],
  ['agents/part5.js', path.join(SRC, 'agents', 'part5.js')],
  ['aggregator.js', path.join(SRC, 'aggregator.js')]
];

const tail = [
  `  root.V14Terminal = {`,
  `    engine: __req('aggregator.js'),`,
  `    indicators: __req('indicators.js'),`,
  `    agents: __req('agents/engine.js')`,
  `  };`,
  `})(typeof window !== 'undefined' ? window : globalThis);`,
  ''
].join('\n');

fs.mkdirSync(path.join(ROOT, 'site-v14'), { recursive: true });
const wrapped = modules.map(([id, file]) => wrap(id, file));
const aliasIdx = modules.findIndex(([id]) => id === 'agents/engine.js');
wrapped.splice(aliasIdx + 1, 0, `  __m['engine.js'] = __m['agents/engine.js'];`);
const out = [banner, ...wrapped, tail].join('\n');
fs.writeFileSync(OUT, out);
console.log('built ' + OUT + ' ' + out.length + ' bytes');
